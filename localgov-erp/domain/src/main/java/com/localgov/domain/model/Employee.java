    /**
     * Division is derived from salary_scale per the 2026 Collective Agreement.
     * Not a stored column - computed on read.
     *
     * Division I:   LGSS/01 - LGSS/07
     * Division II:  LGSS/08 - LGSS/12
     * Division III: LGSS/13 - LGSS/18
     * Division IV:  G1, G2, G3
     */
    public String getDivision() {
        if (salaryScale == null) return null;
        String s = salaryScale.toUpperCase().trim();
        if (s.matches("^LGSS/0[1-7]$")) return "I";
        if (s.matches("^LGSS/0[8-9]$") || s.matches("^LGSS/1[0-2]$")) return "II";
        if (s.matches("^LGSS/1[3-8]$")) return "III";
        if (s.equals("G1") || s.equals("G2") || s.equals("G3")) return "IV";
        return null;
    }

