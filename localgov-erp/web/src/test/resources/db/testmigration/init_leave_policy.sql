-- Audit log table (matches V46 production migration)
CREATE TABLE IF NOT EXISTS leave_calculation_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL,
    leave_request_id BIGINT,
    leave_type VARCHAR(100) NOT NULL,
    division VARCHAR(100),
    start_date DATE,
    requested_days INTEGER NOT NULL,
    adjusted_days INTEGER,
    forfeited_days INTEGER,
    reason VARCHAR(255),
    balance_before INTEGER,
    balance_after INTEGER,
    calculation_mode VARCHAR(50),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    triggered_by VARCHAR(100),
    username VARCHAR(80),
    authority_code VARCHAR(10),
    authority_type VARCHAR(50),
    role VARCHAR(200)
);
