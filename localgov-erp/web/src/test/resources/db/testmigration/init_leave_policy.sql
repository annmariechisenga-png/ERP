-- H2-compatible initialization of leave_policy table.
-- Runs after Hibernate create-drop creates other tables.

CREATE TABLE IF NOT EXISTS leave_policy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leave_type VARCHAR(255),
    division VARCHAR(100),
    accrual_rate DOUBLE PRECISION,
    max_days INTEGER,
    carry_forward INTEGER,
    eligibility VARCHAR(1000),
    fixed_days INTEGER,
    max_accumulation INTEGER,
    max_duration INTEGER,
    advance_notice INTEGER,
    gender_restriction VARCHAR(50) DEFAULT 'ALL',
    day_calculation_mode VARCHAR(50) DEFAULT 'WORKING',
    monthly_limit INTEGER,
    annual_limit INTEGER,
    sick_full_pay_months INTEGER,
    sick_half_pay_months INTEGER,
    sick_full_pay_days_contract INTEGER,
    sick_half_pay_days_contract INTEGER,
    requires_birth_proof BOOLEAN DEFAULT FALSE,
    requires_medical_cert BOOLEAN DEFAULT FALSE,
    advance_notice_days INTEGER DEFAULT 0,
    continuous_leave_limit INTEGER
);

