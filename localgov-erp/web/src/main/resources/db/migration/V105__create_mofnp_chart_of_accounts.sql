-- ---------------------------------------------------------------------
-- 3. Verify coverage
-- ---------------------------------------------------------------------
DO $$
DECLARE
    v_total INTEGER;
    v_by_class RECORD;
BEGIN
    SELECT COUNT(*) INTO v_total FROM mofnp_chart_of_accounts;
    RAISE NOTICE 'MoFNP Chart of Accounts seeded: % accounts total', v_total;

    FOR v_by_class IN
        SELECT mofnp_classification AS cls, COUNT(*) AS cnt
        FROM mofnp_chart_of_accounts
        GROUP BY mofnp_classification
        ORDER BY mofnp_classification
    LOOP
        RAISE NOTICE '  Classification %: % accounts',
            v_by_class.cls, v_by_class.cnt;
    END LOOP;
END $$;

