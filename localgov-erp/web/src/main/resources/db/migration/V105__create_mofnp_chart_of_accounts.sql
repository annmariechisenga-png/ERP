-- =====================================================================
-- V105__create_mofnp_chart_of_accounts.sql
-- MoFNP Chart of Accounts — Complete National Standard
-- =====================================================================
-- Compliance:
--   MoFNP Local Government Accounting and Financial Procedures Manual
--   (December 2023), Section 10.5 through 10.11
--
-- Creates mofnp_chart_of_accounts and seeds ~800 accounts across:
--   1 — Revenue      (Section 10.5, Table 7)
--   2 — Expenses     (Section 10.6, Table 8)
--   3 — Assets       (Section 10.7, Table 9)
--   4 — Liabilities  (Section 10.8, Table 10)
--   5 — Net Assets   (Section 10.9, Table 11)
--   6 — Gains/Losses (Section 10.10, Table 12)
--   7 — Memorandum   (Section 10.11, Table 13)
--
-- Corrections applied to the manual (documented in notes):
--   159099  — Fixed typo from manual (was 158099 in Donor Support)
--   411250  — Fixed duplicate code (manual had 411210 twice)
--
-- Duplicates intentionally skipped (manual typos):
--   311218–311234 — asset duplicates of 311201–311217
--   281010        — expense duplicate within Legal Costs
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Create the table
-- ---------------------------------------------------------------------
CREATE TABLE mofnp_chart_of_accounts (
    account_id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    account_code          VARCHAR(6) NOT NULL UNIQUE,
    account_name          VARCHAR(200) NOT NULL,
    account_type          VARCHAR(20) NOT NULL,
        -- REVENUE, EXPENSE, ASSET, LIABILITY, NET_ASSET, GAIN_LOSS, MEMORANDUM
    mofnp_classification  VARCHAR(2) NOT NULL,
    parent_account_code   VARCHAR(6) REFERENCES mofnp_chart_of_accounts(account_code),
    hierarchy_level       INTEGER NOT NULL DEFAULT 1,
    is_postable           BOOLEAN NOT NULL DEFAULT FALSE,
    is_national_template  BOOLEAN NOT NULL DEFAULT TRUE,
    is_active             BOOLEAN NOT NULL DEFAULT TRUE,
    effective_from        DATE NOT NULL DEFAULT CURRENT_DATE,
    effective_to          DATE,
    notes                 TEXT,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by            UUID,
    updated_at            TIMESTAMPTZ,
    updated_by            UUID,
    CONSTRAINT chk_mofnp_classification CHECK (
        mofnp_classification IN ('1','2','3','4','5','6','7')
    ),
    CONSTRAINT chk_mofnp_account_type CHECK (
        account_type IN (
            'REVENUE','EXPENSE','ASSET','LIABILITY',
            'NET_ASSET','GAIN_LOSS','MEMORANDUM'
        )
    )
);

CREATE INDEX idx_mofnp_coa_classification
    ON mofnp_chart_of_accounts(mofnp_classification);
CREATE INDEX idx_mofnp_coa_parent
    ON mofnp_chart_of_accounts(parent_account_code)
    WHERE parent_account_code IS NOT NULL;
CREATE INDEX idx_mofnp_coa_postable
    ON mofnp_chart_of_accounts(is_postable)
    WHERE is_postable = TRUE;

COMMENT ON TABLE mofnp_chart_of_accounts IS
'National MoFNP Chart of Accounts. Populated from the MoFNP Local '
'Government Accounting Manual (Dec 2023), Sections 10.5–10.11. '
'All rows are national templates; council-specific accounts are added '
'separately with is_national_template = FALSE.';

COMMENT ON COLUMN mofnp_chart_of_accounts.is_postable IS
'Only leaf accounts (postable) accept journal postings. Parent accounts '
'are summary-only.';

